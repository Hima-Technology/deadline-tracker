interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (text: string) => string
  darkMode: boolean
  setDarkMode: (enabled: boolean) => void
  appFont: AppFont
  setAppFont: (font: AppFont) => void
}

export type AppFont = 'space' | 'arial' | 'georgia' | 'system' | 'mono'

const fontFamilies: Record<AppFont, string> = {
  space: '"Space Grotesk", sans-serif',
  arial: 'Arial, Helvetica, sans-serif',
  georgia: 'Georgia, "Times New Roman", serif',
  system: 'system-ui, -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif',
  mono: '"JetBrains Mono", Consolas, monospace',
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    return localStorage.getItem('language') === 'sw' ? 'sw' : 'en'
  })
  const [darkMode, setDarkModeState] = useState(() => localStorage.getItem('darkMode') === 'true')
  const [appFont, setAppFontState] = useState<AppFont>(() => {
    const savedFont = localStorage.getItem('appFont')
    return savedFont && savedFont in fontFamilies ? savedFont as AppFont : 'space'
  })

  useEffect(() => {
    document.documentElement.lang = language
    localStorage.setItem('language', language)
  }, [language])

  useEffect(() => {
    document.documentElement.classList.toggle('dark', darkMode)
    localStorage.setItem('darkMode', String(darkMode))
  }, [darkMode])

  useEffect(() => {
    document.documentElement.style.setProperty('--app-font', fontFamilies[appFont])
    document.documentElement.dataset.appFont = appFont
    localStorage.setItem('appFont', appFont)
  }, [appFont])

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage: setLanguageState,
    t: (text: string) => language === 'sw' ? translations[text] || text : text,
    darkMode,
    setDarkMode: setDarkModeState,
    appFont,
    setAppFont: setAppFontState,
  }), [language, darkMode, appFont])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within LanguageProvider')
  return context
}

export function translate(text: string): string {
  return localStorage.getItem('language') === 'sw' ? translations[text] || text : text
}
